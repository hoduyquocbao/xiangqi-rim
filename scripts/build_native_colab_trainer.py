            "def extract_features(fen):\n",
            "    parts = fen.split()\n",
            "    board_str = parts[0]\n",
            "    side = 0 if len(parts) > 1 and parts[1] == 'w' else 1\n",
            "\n",
            "    grid = [15] * 90\n",
            "    pos = 0\n",
            "    for ch in board_str:\n",
            "        if ch == '/':\n",
            "            continue\n",
            "        elif ch.isdigit():\n",
            "            pos += int(ch)\n",
            "        else:\n",
            "            p = PIECE_MAP.get(ch, -1)\n",
            "            if p >= 0 and pos < 90:\n",
            "                grid[pos] = p\n",
            "            pos += 1\n",
            "\n",
            "    king_piece = 4 if side == 0 else 11\n",
            "    king_sq = -1\n",
            "    for i in range(90):\n",
            "        if grid[i] == king_piece:\n",
            "            king_sq = i\n",
            "            break\n",
            "    if king_sq < 0:\n",
            "        return [], [], side\n",
            "\n",
            "    opp_king_piece = 11 if side == 0 else 4\n",
            "    opp_king_sq = -1\n",
            "    for i in range(90):\n",
